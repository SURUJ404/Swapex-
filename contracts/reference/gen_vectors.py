"""Generates test/v3/GoldenVectors.t.sol from the Python reference model."""
import random
from poolmodel import *

random.seed(2026)
out = []
w = out.append


def lit(n):
    return f"-int256({-n})" if n < 0 else str(n)


w("// SPDX-License-Identifier: GPL-2.0-or-later")
w("// GENERATED by reference/gen_vectors.py. Do not edit by hand.")
w("pragma solidity ^0.8.26;")
w("")
w('import {V3Base} from "./V3Base.t.sol";')
w('import {TickMath} from "../../src/libraries/TickMath.sol";')
w('import {SwapMath} from "../../src/libraries/SwapMath.sol";')
w('import {SqrtPriceMath} from "../../src/libraries/SqrtPriceMath.sol";')
w("")
w("contract GoldenVectorsTest is V3Base {")

# ---- tick math
ticks = [MIN_TICK, -887271, -500000, -100000, -60000, -887, -60, -1, 0, 1, 60, 887, 60000, 100000, 500000, 887271, MAX_TICK]
w("    function test_golden_tickMath() public {")
for t in ticks:
    w(f"        assertEq_(TickMath.getSqrtRatioAtTick({t}), {sqrt_ratio_at_tick(t)});")
    if t < MAX_TICK:
        w(f"        assertEqInt_(TickMath.getTickAtSqrtRatio(uint160({sqrt_ratio_at_tick(t)})), {t});")
w("    }")
w("")

# ---- swap step
w("    function test_golden_swapStep() public {")
w("        uint160 n; uint256 ain; uint256 aout; uint256 fee_;")
for i in range(40):
    L = random.randint(10**12, 10**24)
    t0 = random.randint(-100000, 100000)
    t1 = t0 + random.choice([-1, 1]) * random.randint(1, 5000)
    sp, tg = sqrt_ratio_at_tick(t0), sqrt_ratio_at_tick(t1)
    fee = random.choice([500, 3000, 10000])
    rem = random.randint(1, 10**22) * random.choice([1, -1])
    nxt, ai, ao, fa = swap_step(sp, tg, L, rem, fee)
    w(f"        (n, ain, aout, fee_) = SwapMath.computeSwapStep(uint160({sp}), uint160({tg}), uint128({L}), {lit(rem)}, {fee});")
    w(f"        assertEq_(n, {nxt}); assertEq_(ain, {ai}); assertEq_(aout, {ao}); assertEq_(fee_, {fa});")
w("    }")
w("")

# ---- pool scenario
pool = Pool(3000, 60, Q96)
ME = "me"
steps = []
positions = [(-600, 600, 10**21), (-180, 3000, 5 * 10**20), (-3000, -300, 3 * 10**20)]
w("    function test_golden_poolScenario() public {")
w("        int256 d0; int256 d1; uint256 a0; uint256 a1;")
for lo, hi, L in positions:
    a0, a1 = pool.mint(ME, lo, hi, L)
    w(f"        (a0, a1) = pool.mint(address(this), {lo}, {hi}, {L}, \"\");")
    w(f"        assertEq_(a0, {a0}); assertEq_(a1, {a1});")
swaps = [
    (True, 5 * 10**18, -2000),
    (False, 2 * 10**19, 2500),
    (True, -3 * 10**18, -2900),
    (False, -10**18, 3000),
    (True, 4 * 10**19, -2800),   # crosses several ticks
    (False, 6 * 10**19, 3500),
]
for zfo, amt, limit_tick in swaps:
    lim = sqrt_ratio_at_tick(limit_tick)
    d0, d1 = pool.swap(zfo, amt, lim)
    w(f"        (d0, d1) = pool.swap(address(this), {'true' if zfo else 'false'}, {lit(amt)}, TickMath.getSqrtRatioAtTick({limit_tick}), \"\");")
    w(f"        assertEqInt_(d0, {lit(d0)}); assertEqInt_(d1, {lit(d1)});")
w("        (uint160 sqrtP, int24 tick,,) = pool.slot0();")
w(f"        assertEq_(sqrtP, {pool.sqrt}); assertEqInt_(tick, {pool.tick});")
w(f"        assertEq_(pool.liquidity(), {pool.L});")
w(f"        assertEq_(pool.feeGrowthGlobal0X128(), {pool.fg0}); assertEq_(pool.feeGrowthGlobal1X128(), {pool.fg1});")
for lo, hi, L in positions:
    b0, b1 = pool.burn(ME, lo, hi, L)
    w(f"        (a0, a1) = pool.burn({lo}, {hi}, {L});")
    w(f"        assertEq_(a0, {b0}); assertEq_(a1, {b1});")
    c0, c1 = pool.collect(ME, lo, hi)
    w(f"        (uint128 c0, uint128 c1) = pool.collect(address(this), {lo}, {hi}, type(uint128).max, type(uint128).max);" if (lo, hi, L) == positions[0] else f"        (c0, c1) = pool.collect(address(this), {lo}, {hi}, type(uint128).max, type(uint128).max);")
    w(f"        assertEq_(uint256(c0), {c0}); assertEq_(uint256(c1), {c1});")
w(f"        assertEq_(token0.balanceOf(address(pool)), {pool.bal0}); assertEq_(token1.balanceOf(address(pool)), {pool.bal1});")
w("    }")
w("}")
open('../test/v3/GoldenVectors.t.sol', 'w').write("\n".join(out) + "\n")
print("pool end state:", pool.sqrt, pool.tick, pool.L, "dust", pool.bal0, pool.bal1)
