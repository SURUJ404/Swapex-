"""Generates test/v3/OracleGolden.t.sol from the Python reference model.

Replays a deterministic sequence of warps/mints/swaps/burns against the reference
Pool (whose observation ring buffer was validated in check_oracle.py) and emits the
expected observe() outputs as golden vectors. The Solidity test warps block.timestamp
to the same absolute times (bootstrap aligned at t=0 via vm.warp(0) before initialize)
and asserts the on-chain oracle matches bit-for-bit.
"""
from poolmodel import *

pool = Pool(3000, 60, Q96, cardinality_next=16)
ME = "me"

# (kind, args) executed in order; observe entries are the assertions
ops = [
    ("mint", (-600, 600, 10**21)),
    ("warp", 100),
    ("observe", [0]),
    ("swap", (True, 5 * 10**18, -2000)),
    ("warp", 150),
    ("observe", [0, 50, 100]),
    ("swap", (False, 3 * 10**18, 2500)),
    ("warp", 300),
    ("observe", [0, 100, 200, 300]),
    ("mint", (-3000, 3000, 5 * 10**20)),
    ("warp", 400),
    ("swap", (True, -2 * 10**18, -2500)),  # exact output
    ("warp", 500),
    ("observe", [0, 50, 150, 250, 400]),
    ("burn", (-600, 600, 4 * 10**20)),
    ("warp", 600),
    ("observe", [0, 100, 300]),
]


def lit(n):
    return f"-int256({-n})" if n < 0 else str(n)


out = []
w = out.append
w("// SPDX-License-Identifier: GPL-2.0-or-later")
w("// GENERATED by reference/gen_oracle_vectors.py. Do not edit by hand.")
w("pragma solidity ^0.8.26;")
w("")
w('import {V3Base} from "./V3Base.t.sol";')
w('import {TickMath} from "../../src/libraries/TickMath.sol";')
w("")
w("contract OracleGoldenTest is V3Base {")
w("    function setUp() public override {")
w("        vm.warp(0); // align the bootstrap observation timestamp with the reference model (t=0)")
w("        super.setUp();")
w("        pool.increaseObservationCardinalityNext(16);")
w("    }")
w("")
w("    function test_golden_oracle() public {")
w("        int256 d0; int256 d1; uint256 a0; uint256 a1;")
w("        int56[] memory tc; uint160[] memory spl; uint32[] memory agos;")
w("        int56 tc0; uint160 spl0;")

for kind, args in ops:
    if kind == "warp":
        pool.now = args
        w(f"        vm.warp({args});")
    elif kind == "mint":
        lo, hi, L = args
        a0, a1 = pool.mint(ME, lo, hi, L)
        w(f"        (a0, a1) = pool.mint(address(this), {lo}, {hi}, {L}, \"\");")
        w(f"        assertEq_(a0, {a0}); assertEq_(a1, {a1});")
    elif kind == "swap":
        zfo, amt, limit_tick = args
        lim = sqrt_ratio_at_tick(limit_tick)
        d0, d1 = pool.swap(zfo, amt, lim)
        w(f"        (d0, d1) = pool.swap(address(this), {'true' if zfo else 'false'}, {lit(amt)}, TickMath.getSqrtRatioAtTick({limit_tick}), \"\");")
        w(f"        assertEqInt_(d0, {lit(d0)}); assertEqInt_(d1, {lit(d1)});")
    elif kind == "burn":
        lo, hi, L = args
        b0, b1 = pool.burn(ME, lo, hi, L)
        w(f"        (a0, a1) = pool.burn({lo}, {hi}, {L});")
        w(f"        assertEq_(a0, {b0}); assertEq_(a1, {b1});")
    elif kind == "observe":
        agos = args
        tc, spl = pool.observe(agos)
        agos_lit = ",".join(str(a) for a in agos)
        w(f"        agos = new uint32[]({len(agos)});")
        for i, a in enumerate(agos):
            w(f"        agos[{i}] = {a};")
        w("        (tc, spl) = pool.observe(agos);")
        for i in range(len(agos)):
            w(f"        assertEqInt_(int256(tc[{i}]), {lit(tc[i])});")
            w(f"        assertEq_(uint256(spl[{i}]), {spl[i]});")
        # also assert the single-window convenience read matches the batch entry for secondsAgo=0
        if 0 in agos:
            idx = agos.index(0)
            w(f"        (tc0, spl0) = pool.observeSingle(0);")
            w(f"        assertEqInt_(int256(tc0), {lit(tc[idx])});")
            w(f"        assertEq_(uint256(spl0), {spl[idx]});")

w("        (uint160 sqrtP, int24 tick,,) = pool.slot0();")
w(f"        assertEq_(sqrtP, {pool.sqrt}); assertEqInt_(tick, {pool.tick});")
w(f"        assertEq_(pool.liquidity(), {pool.L});")
w(f"        assertEq_(pool.observationCardinality(), {pool.obs_cardinality});")
w("    }")
w("}")
open("../test/v3/OracleGolden.t.sol", "w").write("\n".join(out) + "\n")
print("oracle golden written; final tick/L:", pool.tick, pool.L, "cardinality:", pool.obs_cardinality)
