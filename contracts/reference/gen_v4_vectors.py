"""Generates test/v4/V4Golden.t.sol from the V4 PoolManager reference model (v4model.py).

The generated test replays the SAME deterministic operation sequence through the Solidity
PoolManager (via the V4Router harness) and asserts every returned BalanceDelta matches the model
bit-for-bit. This is the differential gate that ties the Solidity flash-accounting + concentrated
liquidity math to the Python oracle. Run from contracts/reference:  py gen_v4_vectors.py
"""
from v4model import PoolManagerModel
from refmath import Q96, MIN_SQRT_RATIO, MAX_SQRT_RATIO

# deterministic op sequence on a single pool (fee=3000, spacing=60, init at Q96)
FEE, SPACING = 3000, 60
OPS = [
    # (kind, lo, hi, liquidityDelta / (zfo, amount))  -- currency0=1, currency1=2 in the model
    ("mint", -600, 600, 10**18),
    ("swap", True, 10**17),          # exact-in, sell token0
    ("swap", False, -(5 * 10**16)),  # exact-out, buy token0 (receive token0)
    ("swap", True, 3 * 10**17),      # exact-in, larger, may cross ticks
    ("burn", -600, 600, -(5 * 10**17)), # remove half the liquidity
    ("poke", -600, 600, 0),          # accrue fees only
    ("burn", -600, 600, -(5 * 10**17)), # remove the rest
]


def run_model():
    """Replay OPS through the model, each in its own unlock session (matching the router)."""
    m = PoolManagerModel()
    key = (1, 2, FEE, SPACING)
    m.initialize(key, Q96)
    results = []

    class _Cb:
        def __init__(self, fn):
            self.fn = fn

        def unlockCallback(self, mgr, data):
            return self.fn(mgr)

    def session(fn):
        m.unlock(_Cb(fn), b"")

    for op in OPS:
        kind = op[0]
        if kind == "mint":
            _, lo, hi, liq = op

            def fn(mgr, lo=lo, hi=hi, liq=liq):
                d0, d1 = mgr.modify_liquidity(key, "LP", lo, hi, liq)
                mgr.settle(1, -d0)
                mgr.settle(2, -d1)
                results.append(("mint", d0, d1))

            session(fn)
        elif kind == "swap":
            _, zfo, amt = op

            def fn(mgr, zfo=zfo, amt=amt):
                limit = MIN_SQRT_RATIO + 1 if zfo else MAX_SQRT_RATIO - 1
                d0, d1 = mgr.swap(key, zfo, amt, limit)
                if d0 < 0:
                    mgr.settle(1, -d0)
                elif d0 > 0:
                    mgr.take(1, d0)
                if d1 < 0:
                    mgr.settle(2, -d1)
                elif d1 > 0:
                    mgr.take(2, d1)
                results.append(("swap", d0, d1))

            session(fn)
        elif kind == "burn":
            _, lo, hi, liq = op

            def fn(mgr, lo=lo, hi=hi, liq=liq):
                d0, d1 = mgr.modify_liquidity(key, "LP", lo, hi, liq)
                if d0 > 0:
                    mgr.take(1, d0)
                elif d0 < 0:
                    mgr.settle(1, -d0)
                if d1 > 0:
                    mgr.take(2, d1)
                elif d1 < 0:
                    mgr.settle(2, -d1)
                results.append(("burn", d0, d1))

            session(fn)
        elif kind == "poke":
            _, lo, hi, _ = op

            def fn(mgr, lo=lo, hi=hi):
                d0, d1 = mgr.modify_liquidity(key, "LP", lo, hi, 0)
                if d0 > 0:
                    mgr.take(1, d0)
                if d1 > 0:
                    mgr.take(2, d1)
                results.append(("poke", d0, d1))

            session(fn)
    return results


def lit(n):
    return f"-int256({-n})" if n < 0 else str(n)


def main():
    results = run_model()
    out = []
    w = out.append
    w("// SPDX-License-Identifier: GPL-2.0-or-later")
    w("// GENERATED by reference/gen_v4_vectors.py. Do not edit by hand.")
    w("pragma solidity ^0.8.26;")
    w("")
    w('import {Test} from "forge-std/Test.sol";')
    w('import {PoolManager, SwapParams, ModifyLiquidityParams} from "../../src/v4/PoolManager.sol";')
    w('import {currency} from "../../src/v4/types/Currency.sol";')
    w('import {BalanceDelta, amount0, amount1} from "../../src/v4/types/BalanceDelta.sol";')
    w('import {PoolKey} from "../../src/v4/types/PoolKey.sol";')
    w('import {TickMath} from "../../src/libraries/TickMath.sol";')
    w('import {MockERC20} from "../mocks/MockERC20.sol";')
    w('import {V4Router} from "./PoolManager.t.sol";')
    w("")
    w("uint160 constant Q96v = uint160(1 << 96);")
    w("")
    w("contract V4GoldenTest is Test {")
    w("    PoolManager pm;")
    w("    V4Router router;")
    w("    MockERC20 tokenA;")
    w("    MockERC20 tokenB;")
    w("    PoolKey key;")
    w("    currency curA;")
    w("    currency curB;")
    w("    bool zeroForOneIsA;")
    w("")
    w("    function setUp() public {")
    w("        pm = new PoolManager(address(this));")
    w("        router = new V4Router(pm);")
    w("        tokenA = new MockERC20(\"A\", \"A\", 18);")
    w("        tokenB = new MockERC20(\"B\", \"B\", 18);")
    w("        curA = currency.wrap(address(tokenA));")
    w("        curB = currency.wrap(address(tokenB));")
    w("        // sort currencies by address so the key is valid")
    w("        if (address(tokenA) < address(tokenB)) {")
    w("            key = PoolKey(curA, curB, 3000, 60, address(0));")
    w("            zeroForOneIsA = true;")
    w("        } else {")
    w("            key = PoolKey(curB, curA, 3000, 60, address(0));")
    w("            zeroForOneIsA = false;")
    w("        }")
    w("        tokenA.mint(address(router), 1_000_000e18);")
    w("        tokenB.mint(address(router), 1_000_000e18);")
    w("        router.approveAll(address(tokenA), address(tokenB));")
    w("        router.initialize(key, Q96v);")
    w("    }")
    w("")
    w("    // model currency0 is the pool's currency0, currency1 is currency1.")
    w("    // zeroForOne=true in the model means sell currency0; map that to the sorted key.")
    w("    function _zfo(bool modelZeroForOne) internal view returns (bool) {")
    w("        // model sells token '1' (=currency0) when zeroForOne; currency0 of the sorted key")
    w("        // is tokenA iff zeroForOneIsA. Selling currency0 <=> modelZeroForOne.")
    w("        return modelZeroForOne;")
    w("    }")
    w("")
    w("    function test_golden_poolOps() public {")
    w("        BalanceDelta cd; BalanceDelta fa;")
    i = 0
    for (label, d0, d1) in results:
        i += 1
        if label == "mint":
            w(f"        // op{i}: mint")
            w("        (cd, fa) = router.modifyLiquidity(key, ModifyLiquidityParams(-600, 600, int256(uint256(10**18))));")
            w(f"        assertEq(amount0(cd) + amount0(fa), {lit(d0)}, \"mint d0\");")
            w(f"        assertEq(amount1(cd) + amount1(fa), {lit(d1)}, \"mint d1\");")
        elif label == "swap":
            amt = OPS[i - 1][2]
            zfo = OPS[i - 1][1]
            limit = "TickMath.MIN_SQRT_RATIO + 1" if zfo else "TickMath.MAX_SQRT_RATIO - 1"
            w(f"        // op{i}: swap zfo={zfo} amount={amt}")
            w(f"        cd = router.swap(key, SwapParams(_zfo({'true' if zfo else 'false'}), {lit(amt)}, {limit}));")
            w(f"        assertEq(amount0(cd), {lit(d0)}, \"swap d0\");")
            w(f"        assertEq(amount1(cd), {lit(d1)}, \"swap d1\");")
        elif label == "burn":
            liq = OPS[i - 1][3]
            w(f"        // op{i}: burn liquidity={liq}")
            w(f"        (cd, fa) = router.modifyLiquidity(key, ModifyLiquidityParams(-600, 600, {lit(liq)}));")
            w(f"        assertEq(amount0(cd) + amount0(fa), {lit(d0)}, \"burn d0\");")
            w(f"        assertEq(amount1(cd) + amount1(fa), {lit(d1)}, \"burn d1\");")
        elif label == "poke":
            w(f"        // op{i}: poke (accrue fees)")
            w("        (cd, fa) = router.modifyLiquidity(key, ModifyLiquidityParams(-600, 600, 0));")
            w(f"        assertEq(amount0(cd) + amount0(fa), {lit(d0)}, \"poke d0\");")
            w(f"        assertEq(amount1(cd) + amount1(fa), {lit(d1)}, \"poke d1\");")
    w("    }")
    w("}")
    with open("../test/v4/V4Golden.t.sol", "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote test/v4/V4Golden.t.sol with {len(results)} ops")


if __name__ == "__main__":
    main()
